	public static LanguageProfile Current
	{
		get => _current;
		set
		{
			if (_current.Id != value.Id)
			{
				_current = value;
				SaveLanguagePreference(value.Id);
				OnLanguageChanged?.Invoke();
			}
		}
	}

	public static event Action? OnLanguageChanged;

	private static LanguageProfile InitializeLanguage()
	{
		string? saved = LoadLanguagePreference();
		if (!string.IsNullOrEmpty(saved))
		{
			LanguageProfile? languageProfile = SupportedLanguages.FirstOrDefault(l => l.Id.Equals(saved, StringComparison.OrdinalIgnoreCase));
			if (languageProfile != null)
			{
				return languageProfile;
			}
		}
		string currentSys = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
		return SupportedLanguages.FirstOrDefault(l => l.Id.Equals(currentSys, StringComparison.OrdinalIgnoreCase)) ?? SupportedLanguages[0];
	}

	private static string? LoadLanguagePreference()
	{
		try
		{
			using RegistryKey? registryKey = Registry.CurrentUser.OpenSubKey(RegistrySettingsPath, writable: false);
			return registryKey?.GetValue(LanguageValueName) as string;
		}
		catch
		{
			return null;
		}
	}

	private static void SaveLanguagePreference(string langId)
	{
		try
		{
			using RegistryKey? registryKey = Registry.CurrentUser.CreateSubKey(RegistrySettingsPath);
			registryKey?.SetValue(LanguageValueName, langId);
		}
		catch
		{
		}
	}

	private static string SlavicPlural(int n, string form1, string form2, string form5)
	{
		n = Math.Abs(n) % 100;
		int num = n % 10;
		if (n > 10 && n < 20)
		{
			return form5;
		}
		if (num > 1 && num < 5)
		{
			return form2;
		}
		if (num == 1)
		{
			return form1;
		}
		return form5;
	}

	private static string PolishPlural(int n, string form1, string form2, string form5)
	{
		if (n == 1)
		{
			return form1;
		}
		int num = n % 10;
		int num2 = n % 100;
		if (num >= 2 && num <= 4 && (num2 < 10 || num2 >= 20))
		{
			return form2;
		}
		return form5;
	}
